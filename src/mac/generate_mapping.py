"""Generates C++ keycode mapping headers for macOS."""

import optparse
import sys


class Mapping(object):

  def __init__(self, options):
    self._mapname = options.mapname
    self._key_type = options.key_type
    self._result_type = options.result_type
    self._filename = options.filename

  def ParseEntry(self, line):
    """Parses a single TSV line into (is_shift, key, value), or None.

    Args:
      line: A single line from the mapping TSV file.

    Returns:
      A tuple of (is_shift, key, value), or None if the line does not contain
      two tab-delimited columns.
    """
    columns = line.strip().split('\t')
    if len(columns) != 2:
      return None
    key, value = columns
    is_shift = False
    if key.startswith('Shift '):
      is_shift = True
      key = key[len('Shift ') :]

    if self._key_type == 'unsigned short' and not key.startswith('kVK_'):
      key = 'kVK_ANSI_' + key

    if self._result_type == 'const char *':
      value = '"%s"' % ''.join(r'\x%02x' % b for b in value.encode('utf-8'))
    elif self._result_type == 'KeyEvent::SpecialKey':
      value = 'KeyEvent::' + value
    return is_shift, key, value

  def PrintMap(self, name, entries):
    """Prints a constexpr CreateFlatMap definition if entries is non-empty."""
    if not entries:
      return
    print(
        'constexpr auto k%s = mozc::CreateFlatMap<%s, %s>({'
        % (name, self._key_type, self._result_type)
    )
    for key, value in entries:
      print('    {%s, %s},' % (key, value))
    print('});')

  def Print(self):
    """Generates the C++ header mapping table to stdout."""
    entries = []
    shift_entries = []
    with open(self._filename, encoding='utf-8') as f:
      for line in f:
        parsed = self.ParseEntry(line)
        if parsed is None:
          continue
        is_shift, key, value = parsed
        if is_shift:
          shift_entries.append((key, value))
        else:
          entries.append((key, value))

    print("""// This file is automatically generated by
// generate_mapping.py.
// Do not edit directly and do not include this from any file other
// than KeyCodeMap.mm

namespace {""")
    self.PrintMap(self._mapname, entries)
    self.PrintMap(self._mapname + 'Shift', shift_entries)
    print('}  // namespace')


def ParseOption():
  """Parse command line options."""
  parser = optparse.OptionParser()
  parser.add_option('--mapname', dest='mapname')
  parser.add_option('--key_type', dest='key_type')
  parser.add_option('--result_type', dest='result_type')
  parser.add_option('--filename', dest='filename')
  options, unused_args = parser.parse_args()

  if not options.mapname:
    print('Error: the output map name should be specified.')
    sys.exit(2)
  if not options.key_type:
    options.key_type = 'unsigned short'
  if not options.result_type:
    print('Error: the result type of the output map should be speicified.')
  if not options.filename:
    print('Error: the file name is not specified.')
  return options


def main():
  options = ParseOption()
  Mapping(options).Print()


if __name__ == '__main__':
  main()
